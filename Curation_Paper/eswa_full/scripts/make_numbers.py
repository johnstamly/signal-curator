"""numbers.tex generator (Task 14, ruling R28).  From the repo root:

    conda run --no-capture-output -n AI python Curation_Paper/eswa_full/scripts/make_numbers.py --partial
    conda run --no-capture-output -n AI python Curation_Paper/eswa_full/scripts/make_numbers.py --final

--partial  skips a study whose JSON is absent and lists it in the header.
--final    refuses (exit 2) when any registered study JSON is absent.
E1-E4 read results/<name>_s20.json (Stage 2, 20 seeds) when it exists and fall back to the Stage-1 file
otherwise; the run prints which stage each study came from.  --require-stage2 (use it with --final)
refuses (exit 12) when any of the four *_s20.json files is absent.  A paired difference that spans a
Stage-1 and a Stage-2 file refuses (exit 13).
Other refusals have their own exit codes (see lib/numbers_core.py).  Nothing is written on a
refusal.  Output: Curation_Paper/eswa_full/latex/numbers.tex (never the short paper's latex/).
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[3]
if str(REPO) not in sys.path:
    sys.path.insert(0, str(REPO))

import numpy as np  # noqa: E402

from Curation_Paper.eswa_full.lib import numbers_core as C  # noqa: E402
from Curation_Paper.eswa_full.lib import numbers_registry as R  # noqa: E402
from Curation_Paper.eswa_full.lib.metrics import bootstrap_ci  # noqa: E402
from Curation_Paper.eswa_full.lib.protocol import PKG_ROOT, input_hashes, load_config  # noqa: E402

FORBIDDEN_OUT = [REPO / "Curation_Paper" / "latex", REPO / "latex"]
DEFAULT_OUT = PKG_ROOT / "latex" / "numbers.tex"

HEADER = r"""% numbers.tex -- GENERATED by Curation_Paper/eswa_full/scripts/make_numbers.py; do not edit.
% Every reported value is a macro; no number in the manuscript is typed by hand.
%
% Conventions
%   * Names: \<Study><Metric><Variant><Budget>, CamelCase, letters only (LaTeX names cannot hold
%     digits; numbers are spelled: \EoneAccAlBsix = E1, accuracy, AL pipeline, budget 600).
%     Study prefixes: Ezero..Eeleven = E0..E11, Efourteen = E14, EfourFoldZero/EfiveFoldZero =
%     fold-0 clean slice of E4/E5.  Config tags: Al = uncertainty-with-oracle on L_AL,
%     Rand = random on L_rand, RandAl = random on L_AL.  B<number> = labelling budget.
%   * Units: accuracies, recalls, rates, fractions in percent with one decimal and \%;
%     differences in percentage points (\,pp, signed); correlations and trendability with
%     three decimals; counts as integers with {,} thousands separators; seconds with one decimal.
%   * A macro named X and X+Ci come in pairs: X = mean over seeds, XCi = 95 % percentile
%     bootstrap CI over seeds written "a--b" (the seeds are treated as iid units).
%   * "n/a" = the quantity is not defined for that cell (e.g. recovery rate when no label was
%     flipped); any other NaN stops the generator.
%   * The comment above each macro is "<json file> :: <key path> | seeds: <n>" (E1-E4 name their
%     *_s20.json file and 20 seeds once Stage 2 exists, else the Stage-1 file and 5); a paired
%     difference reads "A MINUS B"; a CI reads "lo path & hi path".  Key paths:
%     a.b = key, a["k|x"] = key with special characters, a[3] = list index,
%     a[budget=600] = the list element whose field budget equals 600.
%   * Accuracy = agreement with one operator's labels.  BAD = 0, GOOD = 1.
"""


# ------------------------------------------------------------------ loading and checks
def load_json(path: Path) -> dict:
    # Python json accepts the bare NaN that json.dumps wrote
    return json.loads(path.read_text(encoding="utf-8"))


def label_of(study: R.Study, d: dict | None = None) -> str:
    """The file a study was actually read from (its *_s20.json when Stage 2 was preferred)."""
    src = (d or {}).get("_source")
    if src:
        return src["file"]
    return study.file or f"computed:{study.key}"


def stage_report(data: dict, studies=None) -> list[tuple[str, str, str, object]]:
    """[(study key, stage, file, n_seeds)] of the Stage-2 capable studies that are loaded."""
    out = []
    for st in (studies or R.STUDIES):
        if st.stage2 and st.key in data:
            d = data[st.key]
            out.append((st.key, C.stage_of(d), label_of(st, d), d.get("n_seeds")))
    return out


def load_studies(results_dir: Path, cfg: dict, *, studies=None, partial: bool = False,
                 notes: list | None = None) -> tuple[dict, list[str]]:
    """({study key: data}, [absent study keys]).

    E1-E4 (``Study.stage2``) read ``<stem>_s20.json`` (Stage 2, 20 seeds) when it exists and fall back
    to the Stage-1 file otherwise; the file used is recorded in ``data["_source"]``.

    partial=True: a computed (cell-reading) study whose cells carry mixed code keys -- a rerun in
    progress -- counts as absent and the reason is appended to ``notes``.  Hash mismatches and every
    other refusal still propagate, and --final never sets ``partial``."""
    data, absent = {}, []
    for st in (studies or R.STUDIES):
        if st.loader is not None:
            try:
                d = st.loader(cfg, results_dir)
            except C.MixedCodeKeys as e:
                if not partial:
                    raise
                d = None
                if notes is not None:
                    notes.append(f"{st.key}: cells not yet consistent, treated as absent ({e})")
        else:
            p = Path(results_dir) / st.file
            if st.stage2:
                p2 = Path(results_dir) / C.s20_name(st.file)
                if p2.is_file():
                    d = load_json(p2)
                    C.check_stage2_file(p2.name, d, cfg["seeds_stage2"])
                    d["_source"] = {"file": p2.name, "stage": "stage2"}
                else:
                    d = load_json(p) if p.is_file() else None
                    if d is not None:
                        d["_source"] = {"file": st.file, "stage": "stage1"}
            else:
                d = load_json(p) if p.is_file() else None
        if d is None:
            absent.append(st.key)
        else:
            data[st.key] = d
    return data, absent


def check_all(data: dict, frozen: dict, studies=None) -> None:
    """Hash, provenance, dirty and cross-study code-key refusals."""
    per = {}
    for st in (studies or R.STUDIES):
        if st.key not in data:
            continue
        d = data[st.key]
        C.check_hashes(st.key, d, frozen)
        C.check_provenance_present(st.key, d, st.mode)
        per[st.key] = C.code_keys(d, st.kind)
        C.check_dirty(st.key, d)
    C.check_cross_study_keys(per)


# ------------------------------------------------------------------ evaluation
def seeds_of(spec, d, where):
    if spec is None:
        return None
    if isinstance(spec, int):
        return spec
    v = C.resolve(d, spec, where=where)
    return len(v) if isinstance(v, (list, tuple)) else int(v)


def seed_ids_of(spec, d, where):
    """The list of seeds next to a ``.../n_seeds`` count (``.../seeds``), or None when the spec is
    not such a count or the sibling list is absent (identity then falls back to the count)."""
    if not (isinstance(spec, tuple) and spec and spec[-1] == "n_seeds"):
        return None
    try:
        v = C.resolve(d, spec[:-1] + ("seeds",), where=where)
    except C.KeyPathMissing:
        return None
    return list(v) if isinstance(v, (list, tuple)) else None


def _to_float(x):
    return float(x) if isinstance(x, (int, float)) and not isinstance(x, bool) else x


def evaluate(m: R.Macro, datas: dict, labels: dict) -> tuple[str, str]:
    """(value text, comment text) of one macro; raises a Refusal."""
    d = datas[m.study]
    lab = labels[m.study]
    n = seeds_of(m.seeds, d, lab)
    if m.minus is not None:
        ms = m.minus_study or m.study
        d2, lab2 = datas[ms], labels[ms]
        n2 = seeds_of(m.minus_seeds, d2, lab2)
        C.check_same_stage(m.name, C.stage_of(d), C.stage_of(d2))
        C.check_seed_match(m.name, n, n2)
        ia, ib = seed_ids_of(m.seeds, d, lab), seed_ids_of(m.minus_seeds, d2, lab2)
        if ia is not None and ib is not None:
            C.check_seed_identity(m.name, ia, ib)
        a =C.resolve(d, m.path, where=lab)["values"]
        b = C.resolve(d2, m.minus, where=lab2)["values"]
        C.check_seed_match(m.name, len(a), len(b))
        diffs = [x - y for x, y in zip(a, b)]
        for x in diffs:
            C.check_value(m.name, f"{lab} :: {C.render_path(m.path)} MINUS {C.render_path(m.minus)}", x,
                          not_defined=False)
        if m.part == "value":
            val = C.fmt_value(float(np.mean(diffs)), m.kind)
        else:
            lo, hi = bootstrap_ci(diffs)
            val = C.fmt_ci(lo, hi, m.kind)
        pa = f"{C.render_path(m.path)}.values"
        pb = f"{C.render_path(m.minus)}.values"
        other = "" if lab2 == lab else f" ({lab2})"
        comment = f"{lab} :: {pa} MINUS {pb}{other} | seeds: {C.seed_label(n)}"
        return val, comment
    if m.part == "ci":
        lo_p, hi_p = m.ci_paths
        lo, hi = C.resolve(d, lo_p, where=lab), C.resolve(d, hi_p, where=lab)
        ok = (C.check_value(m.name, f"{lab} :: {C.render_path(lo_p)}", lo, not_defined=m.not_defined)
              & C.check_value(m.name, f"{lab} :: {C.render_path(hi_p)}", hi, not_defined=m.not_defined))
        val = C.fmt_ci(lo, hi, m.kind) if ok else C.NA_TEXT
        comment = f"{lab} :: {C.render_path(lo_p)} & {C.render_path(hi_p)} | seeds: {C.seed_label(n)}"
        return val, comment
    x = C.resolve(d, m.path, where=lab)
    comment = f"{lab} :: {C.render_path(m.path)} | seeds: {C.seed_label(n)}"
    if m.kind in ("text", "bool"):
        return C.fmt_value(x, m.kind), comment
    if not C.check_value(m.name, f"{lab} :: {C.render_path(m.path)}", x, not_defined=m.not_defined):
        return C.NA_TEXT, comment
    return C.fmt_value(x, m.kind), comment


def expand(data: dict, studies=None) -> list[R.Macro]:
    out = []
    for st in (studies or R.STUDIES):
        if st.key in data:
            out += st.builder(data[st.key])
    return out


def check_names(macros) -> None:
    seen = set()
    for m in macros:
        C.check_name(m.name)
        if m.name in seen:
            raise C.BadMacroName(f"duplicate macro name {m.name}")
        seen.add(m.name)


def render(data: dict, absent: list[str], mode: str, studies=None) -> tuple[str, dict]:
    """The full numbers.tex text and {study: macro count}."""
    studies = studies or R.STUDIES
    macros = expand(data, studies)
    check_names(macros)
    labels = {st.key: label_of(st, data.get(st.key)) for st in studies}
    lines = [HEADER.rstrip("\n")]
    lines.append(f"% mode: {mode}")
    keys = {st.key: C.code_keys(data[st.key], st.kind) for st in studies if st.key in data}
    for sk, kk in keys.items():
        if kk:
            lines.append(f"% code keys {sk}: " + ", ".join(f"{k}={v[:12]}" for k, v in sorted(kk.items())))
    lines.append("% stage sources (E1-E4 use the 20-seed *_s20.json file when it exists, else Stage 1): "
                 + (", ".join(f"{k}={stg} ({f}, {C.seed_label(n)} seeds)"
                              for k, stg, f, n in stage_report(data, studies)) or "none"))
    lines.append("% studies included: " + ", ".join(k for k in (s.key for s in studies) if k in data))
    lines.append("% studies SKIPPED (JSON absent, --partial): " + (", ".join(absent) or "none"))
    counts, skipped, cur = {}, [], None
    for m in macros:
        if m.minus_study and m.minus_study not in data:       # needs a study that is absent
            skipped.append(m.name)
            continue
        if m.study != cur:
            cur = m.study
            lines.append("")
            lines.append(f"% ===== {cur} ({labels[cur]}) =====")
        val, comment = evaluate(m, data, labels)
        counts[m.study] = counts.get(m.study, 0) + 1
        lines.append(f"% {comment}")
        lines.append(f"\\newcommand{{\\{m.name}}}{{{val}}}")
    lines.insert(lines.index(
        "% studies SKIPPED (JSON absent, --partial): " + (", ".join(absent) or "none")) + 1,
        "% macros SKIPPED (their comparison partner study is absent): "
        + (", ".join(skipped) or "none"))
    return "\n".join(lines) + "\n", counts


# ------------------------------------------------------------------ main
def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description="generate numbers.tex from the study JSONs")
    g = ap.add_mutually_exclusive_group(required=True)
    g.add_argument("--partial", action="store_true", help="skip (and list) absent studies")
    g.add_argument("--final", action="store_true", help="refuse when any study JSON is absent")
    ap.add_argument("--require-stage2", action="store_true",
                    help="refuse (exit 12) unless e01/e02/e03/e04_compare are all read from *_s20.json")
    ap.add_argument("--results-dir", default=None)
    ap.add_argument("--out", default=None)
    ap.add_argument("--seed-list", default=None,
                    help="comma list: seeds of the fold-0 re-score (smoke runs; needs --results-dir)")
    args = ap.parse_args(argv)
    if args.seed_list and not args.results_dir:
        print("REFUSING: --seed-list needs --results-dir", file=sys.stderr)
        return 4
    cfg = load_config()
    if args.seed_list:
        cfg["seeds_stage1"] = [int(x) for x in args.seed_list.split(",") if x]
    rdir = Path(args.results_dir) if args.results_dir else PKG_ROOT / "results"
    if args.results_dir:
        cfg["results_dir"] = str(rdir)
    out = Path(args.out) if args.out else DEFAULT_OUT
    try:
        C.check_output_path(out, FORBIDDEN_OUT)
        notes: list[str] = []
        data, absent = load_studies(rdir, cfg, partial=args.partial, notes=notes)
        for n in notes:
            print(f"NOTE: {n}", file=sys.stderr)
        if args.require_stage2:
            C.check_require_stage2({st.key: C.stage_of(data[st.key]) if st.key in data else None
                                    for st in R.STUDIES if st.stage2})
        if args.final:
            C.check_final(absent)
        check_all(data, input_hashes(cfg))
        text, counts = render(data, absent, "final" if args.final else "partial")
        print("stage sources:", "; ".join(f"{k}={stg} ({f}, {C.seed_label(n)} seeds)"
                                          for k, stg, f, n in stage_report(data)) or "none")
    except C.Refusal as e:
        print(f"REFUSING ({type(e).__name__}, exit {e.code}): {e}", file=sys.stderr)
        return e.code
    out.parent.mkdir(parents=True, exist_ok=True)
    with open(out, "w", encoding="utf-8", newline="\n") as fh:      # LF on every platform
        fh.write(text)
    print(f"-> {out}: {sum(counts.values())} macros", counts)
    print("skipped (absent):", absent or "none")
    return 0


if __name__ == "__main__":
    sys.exit(main())
